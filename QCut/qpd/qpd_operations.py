# Maps gate_name (from CutLocation.gate_name) to its hand-derived QPD list. Gates listed
# here use the table verbatim, everything else is generated by QCut.qpd_generate. New
# entries are only worth adding where the generated table is worse, as it can be for a
# gate whose Weyl frame needs extra local `u` gates that a hand derivation avoids.
QPD_REGISTRY: dict[str, list] = {
    "cz": cz_qpd,
    "swap": swap_qpd,
    "iswap": iswap_qpd,
}


def qpd_for_location(cut: CutLocation | SingleQubitCutLocation) -> list[dict]:
    """Return the QPD to use for one cut location.

    Wire cuts use the identity channel decomposition. Gate cuts prefer the hand-derived
    table in ``QPD_REGISTRY`` and otherwise generate one from the gate's matrix. The
    result is cached on the cut location, which is needed both to size the experiment
    tensor and to expand it.

    Raises:
        NotImplementedError: a gate cut with neither a table nor a usable gate.
        TypeError: an unrecognised cut location type.
    """
    if isinstance(cut, SingleQubitCutLocation):
        return identity_qpd
    if not isinstance(cut, CutLocation):
        raise TypeError(f"Unknown cut type: {type(cut)}")
    if cut._qpd is not None:
        return cut._qpd

    if cut.gate_name in QPD_REGISTRY:
        qpd = QPD_REGISTRY[cut.gate_name]
    elif cut.gate is not None:
        qpd = qpd_from_gate(cut.gate)
    else:
        raise NotImplementedError(
            f"No QPD available for gate '{cut.gate_name}'. Cut it with "
            "cutGate(<gate>, control, target) so the gate travels with the cut and a "
            "decomposition can be generated from it."
        )
    cut._qpd = qpd
    return qpd


def qpd_for_bundle(bundle: Bundle, cut_locations: list) -> list[dict]:
    """Return the QPD shared by a bundle of cut locations.

    A bundle of one falls through to :func:`qpd_for_location`. Larger bundles get the
    joint decomposition, whose operations act on one qubit per cut.

    Raises:
        QCutError: a bundle was planned that has no joint decomposition.
    """
    if bundle.kind == "cc_wire":
        return locc_wire_qpd(bundle.size)
    if bundle.size == 1:
        return qpd_for_location(cut_locations[bundle.anchor])

    gates = [joint_gate(cut_locations[cut]) for cut in bundle.cuts]
    qpd = joint_rotation_qpd_from_gates(gates, bundle.flipped)
    if qpd is None:  # pragma: no cover - plan_bundles checks this first
        raise QCutError(
            f"bundle {bundle.cuts} has no joint decomposition, which means one of its "
            "gates is not equivalent to a single-axis rotation"
        )
    return qpd


def default_bundles(cut_locations: list) -> list[Bundle]:
    """Return one single-cut bundle per location, the no-bundling arrangement."""
    return [Bundle((index,), "single") for index in range(len(cut_locations))]


def _spread(bundles: list[Bundle], choice: tuple, num_cuts: int) -> tuple[dict, ...]:
    """Turn one term per bundle into one entry per cut location.

    The anchor of each bundle keeps the operations and the whole coefficient, so
    multiplying the per-cut coefficients together still gives the term's coefficient.
    """
    per_cut: dict[int, dict] = {}
    for bundle, term in zip(bundles, choice):
        per_cut.update(flatten_term(bundle, term))
    return tuple(per_cut[index] for index in range(num_cuts))


def bundle_gamma(bundle: Bundle, cut_locations: list) -> float:
    """Return a bundle's sampling overhead without building its QPD.

    Every case has a closed form, which is what makes it cheap enough to cost a whole
    cutting plan before committing to one.
    """
    if bundle.kind == "cc_wire":
        return gamma_locc(bundle.size)
    if bundle.size > 1:
        thetas = [
            single_axis_theta(joint_gate(cut_locations[cut])) for cut in bundle.cuts
        ]
        return gamma_joint(thetas)

    cut = cut_locations[bundle.anchor]
    if isinstance(cut, SingleQubitCutLocation):
        return gamma(identity_qpd)
    if cut.gate_name in QPD_REGISTRY:
        return gamma(QPD_REGISTRY[cut.gate_name])
    if cut.gate is not None:
        return gamma_for_gate(cut.gate)
    raise NotImplementedError(
        f"No QPD available for gate '{cut.gate_name}', so its cost is unknown."
    )


def plan_cost(cut_circuit, options, respect_backend: bool = True) -> float:
    """Return the total sampling overhead a split would cost.

    Includes whatever joint decompositions the split allows, which is the point: two
    splits of the same circuit can permit different bundles, so their costs cannot be
    compared without planning the bundles for each.

    ``respect_backend`` applies the same veto the experiment builder does, without which
    a transpiled split is costed with bundles its backend cannot run. Turn it off to ask
    what the cuts would cost on a device that could run anything.
    """
    subcircuits = [subcircuit.copy() for subcircuit in cut_circuit.subcircuits]
    _remove_obsm_2(subcircuits)
    backend = getattr(cut_circuit, "backend", None) if respect_backend else None
    bundles = plan_bundles(
        cut_circuit.cut_locations,
        subcircuits,
        options,
        announce=False,
        fits=coupling_filter(cut_circuit.cut_locations, subcircuits, backend),
    )
    total = 1.0
    for bundle in bundles:
        total *= bundle_gamma(bundle, cut_circuit.cut_locations)
    return total


def _insert_wire_cut_qpd(
    ind,
    op,
    subcircuit,
    offset,
    qpd_qubits,
    qpd,
    classical_bit_index,
    inserted_operations,
):
    if "Meas" in op.operation.name:  # if measure channel remove placeholder
        # and insert current
        # qpd operation
        qubit_index = subcircuit.find_bit(op.qubits[0]).index
        subcircuit.data.pop(ind + offset)  # remove placeholder
        # measure channel
        qpd_qubits.append(qubit_index)  # store index
        qubits_for_operation = [subcircuit.qubits[qubit_index]]
        meas_op = qpd[int(op.operation.name.split("_")[-1])]["op_0"]
        if meas_op.name == "id-meas":  # if identity measure channel
            # store indices
            # remove extra classical bits and registers
            # _adjust_cregs(subcircuit)
            for subop in reversed(meas_op.data):
                subcircuit._data.insert(
                    ind + offset,
                    CircuitInstruction(
                        operation=subop.operation, qubits=qubits_for_operation
                    ),
                )
        else:
            for subop in reversed(meas_op.data):
                if subop.operation.name == "measure":
                    subcircuit._data.insert(
                        ind + offset,
                        CircuitInstruction(
                            operation=subop.operation,
                            qubits=qubits_for_operation,
                            clbits=[subcircuit.cregs[0][classical_bit_index]],
                        ),
                    )
                else:
                    subcircuit._data.insert(
                        ind + offset,
                        CircuitInstruction(
                            operation=subop.operation,
                            qubits=qubits_for_operation,
                        ),
                    )

            # increment classical bit counter
            classical_bit_index += 1

        inserted_operations += 1
        offset += len(meas_op.data) - 1

    if "Init" in op.operation.name:
        subcircuit.data.pop(ind + offset)
        init_op = qpd[int(op.operation.name.split("_")[-1])]["op_1"]
        qubits_for_operation = [
            subcircuit.qubits[subcircuit.find_bit(x).index] for x in op.qubits
        ]
        for subop in reversed(init_op.data):
            subcircuit._data.insert(
                ind + offset,
                CircuitInstruction(
                    operation=subop.operation, qubits=qubits_for_operation
                ),
            )

        inserted_operations += 1
        offset += len(init_op) - 1

    return offset, classical_bit_index, inserted_operations


